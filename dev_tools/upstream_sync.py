"""Preview/apply public task updates from an exact Git commit; never import it.

Usage: python dev_tools/upstream_sync.py --source PATH [--ref HEAD] [--apply]
No network operation or execution of upstream Python/binaries takes place.
Local changes and deletions are conflicts, including during the first import.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path
import subprocess
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from dev_tools.upstream_policy import CORE_COMMIT, CORE_URL, UPSTREAM_URL, EXCLUDED_TASKS, CORE_FALLBACK_TASKS, selected, adapt
from deploy.project_update import PROJECT_REPOSITORY, PROJECT_BRANCH


def git(root, *args):
    return subprocess.check_output(["git", "-C", str(root), *args])


def digest(data):
    return hashlib.sha256(data).hexdigest() if data is not None else None


def normalized_digest(name, data):
    if data is not None and Path(name).suffix.lower() not in {".png", ".jpg", ".jpeg", ".gif"}:
        data = data.replace(b"\r\n", b"\n")
    return digest(data)


def build_sources(source, ref, root=ROOT):
    commit = git(source, "rev-parse", "--verify", f"{ref}^{{commit}}").decode().strip()
    core_model = git(root, "show", f"{CORE_COMMIT}:module/config/config_model.py").decode("utf-8-sig").replace("\r\n", "\n")
    rendered, upstream = {}, {}
    with zipfile.ZipFile(io.BytesIO(git(root, "archive", "--format=zip", CORE_COMMIT))) as core_archive:
        for name in core_archive.namelist():
            parts = name.split("/")
            if len(parts) > 2 and parts[0] == "tasks" and parts[1] in CORE_FALLBACK_TASKS and not name.endswith("/"):
                rendered[name] = core_archive.read(name)
    with zipfile.ZipFile(io.BytesIO(git(source, "archive", "--format=zip", commit))) as archive:
        for entry in archive.infolist():
            if entry.is_dir() or not selected(entry.filename):
                continue
            if (entry.external_attr >> 16) & 0o170000 == 0o120000:
                raise ValueError(f"Symlinks are not imported: {entry.filename}")
            data = archive.read(entry)
            upstream[entry.filename] = digest(data)
            rendered[entry.filename] = adapt(entry.filename, data, core_model)
    pages = sorted(name.split("/")[1] for name in rendered if name.startswith("tasks/") and name.endswith("/page.py") and len(name.split("/")) == 3)
    rendered["module/compat/upstream_catalog.py"] = (
        '"""Generated by dev_tools/upstream_sync.py from the pinned public tree."""\n'
        f"PAGE_TASKS = {pages!r}\n").encode("utf-8")
    return commit, rendered, upstream


def plan_update(root, rendered, previous, baseline):
    actions, conflicts = [], []
    for name in sorted(set(rendered) | set(previous)):
        path = root / name
        if path.is_symlink() or not path.resolve().is_relative_to(root.resolve()):
            raise ValueError(f"Target escapes checkout: {name}")
        if path.exists() and not path.is_file():
            conflicts.append(name)
            continue
        current = path.read_bytes() if path.is_file() else None
        target = rendered.get(name)
        if current == target:
            continue
        # Text checkouts may use CRLF; tolerate only that Git line-ending change.
        current_hash = digest(current)
        normalized_hash = normalized_digest(name, current)
        expected = previous.get(name, {}).get("installed_sha256")
        expected_normalized = previous.get(name, {}).get("installed_normalized_sha256", expected)
        if name not in previous:
            expected = digest(baseline.get(name))
            expected_normalized = normalized_digest(name, baseline.get(name))
        if current_hash != expected and normalized_hash != expected_normalized:
            conflicts.append(name)
        else:
            actions.append((name, target))
    return actions, conflicts


def main():
    sys.stdout.reconfigure(encoding="utf-8", errors="backslashreplace")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--ref", default="HEAD")
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--verbose", action="store_true", help="List each changed file")
    args = parser.parse_args()
    manifest_path = ROOT / "upstream/manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else {}
    commit, rendered, upstream = build_sources(args.source.resolve(), args.ref)
    baseline = {}
    if not manifest:
        with zipfile.ZipFile(io.BytesIO(git(ROOT, "archive", "--format=zip", CORE_COMMIT))) as archive:
            baseline = {name: archive.read(name) for name in rendered if name in archive.namelist()}
    actions, conflicts = plan_update(ROOT, rendered, manifest.get("files", {}), baseline)
    print(f"YYS {commit}: {len(rendered)} selected files, {len(actions)} changes, {len(conflicts)} conflicts")
    for name in conflicts:
        print(f"CONFLICT {name}")
    if args.verbose:
        for name, data in actions:
            print(f"{'DELETE' if data is None else 'UPDATE'} {name}")
    if conflicts:
        return 2
    if not args.apply:
        print("Preview only. Review the diff after --apply and run dev_tools/verify_port.py.")
        return 0
    # Preflight covers the whole selection before any mutation, so a conflict
    # never causes a partial update. Keep local patches in the policy/adapters.
    for name, data in actions:
        path = ROOT / name
        if data is None:
            path.unlink(missing_ok=True)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    manifest = {
        "schema_version": 1, "project_url": PROJECT_REPOSITORY, "project_branch": PROJECT_BRANCH,
        "core_url": CORE_URL, "core_commit": CORE_COMMIT,
        "upstream_url": UPSTREAM_URL, "upstream_commit": commit,
        "excluded_tasks": sorted(EXCLUDED_TASKS),
        "core_fallback_tasks": sorted(CORE_FALLBACK_TASKS),
        "files": {name: {"upstream_sha256": upstream.get(name), "installed_sha256": digest(data),
                         "installed_normalized_sha256": normalized_digest(name, data)}
                  for name, data in sorted(rendered.items())},
    }
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
